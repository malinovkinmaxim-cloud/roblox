--[[
	WeaponData - the ACTIVE abilities (they fire by themselves) and their EVOLUTIONS.

	Every ability has a Kind: one behaviour function in Sim/CombatManager.lua (and one visual
	in client WeaponFx). Many abilities share a Kind with different numbers and looks.

	  Category  PROJECTILE / AREA / MELEE / SUMMON / DEFENSIVE / SPECIAL (passives live in UpgradeData)
	  Rarity    shared/Rarity.lua (how often it shows up in level-up offers)
	  Base      stats at level 1;  Levels[n] = additive changes + card text
	  Unlock    Default = true, Fragments, Achievement, or Secret (a discovered secret)
	  Evolution { From = ability, With = passive }: a Mythic form offered when From is at max
	            level and the passive is owned (EVOLUTION AVAILABLE)

	Stats (scaled by the player, shared/Stats.lua):
	  Damage x Might   Cooldown x attack speed   Amount + Amount (unless NoAmount)
	  Radius, Orbit, Length x Area   Range x Range   Speed x projectile speed
	  Duration x Duration   Burn x Burn mastery

	Levels change BEHAVIOUR, not only numbers: a level row with New = true unlocks a mechanic
	(the card highlights it). Mechanic keys (Sim/CombatManager.lua; level-up upgrades and items
	add to the same keys, shared/UpgradeData.lua / ItemData.lua):
	  Ricochet n    a straight shot bounces to n more enemies     SplitEnd n  the last hit splits into n shards
	  ExplodeEnd r  the last hit explodes                         Return x    shots fly back (x damage)
	  SlowHit f     hits slow by f            Stun s   hits stun normal enemies s seconds
	  BurnHit d     hits burn (d per second)  ChainHit n  every hit zaps n enemies nearby
	  Weaken f      hits mark: +f damage taken for 3 s
	  Echo n        every n-th cast fires twice                   Aftershock n  impacts repeat as a wave
	  DeathBlast r  enemies killed by it explode                  DeathBurn   ... spread their fire
	  Spread        enemies dying in a cloud leave a new cloud    LastBlast r the last chain target explodes
	  Collapse r    a vortex ends in a blast                      CloneBlast r the clone explodes at the end

	The list order is the network id (uint8): append at the end.
]]

